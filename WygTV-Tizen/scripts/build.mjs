// Builds www/ (the TV app's files) from WygDesktop's screens: node scripts/build.mjs
// - copies WygDesktop/src/renderer, hls.js, mpegts.js and fflate (gzip guides)
// - wraps the desktop's m3u.js, xmltv.js, hdhr.js and tablo.js so they run in the page (js/desktop-modules.js)
// - adds web/tizen-bridge.js, which stands in for the desktop app's main process, web/tizen-avplay.js (video
//   in Samsung's AVPlay) and web/tizen.css
// - makes the CSS work on Tizen 5.5 (2020 TVs, Chromium 69): flex `gap`, `aspect-ratio`, `min()` and `:has()`
//   are newer than that, so the build adds fallbacks that js/tizen-legacy.js switches on only when needed
// - lowers all JavaScript and CSS to Chrome 69 with esbuild (`??`, `inset` and so on)
// - writes config.xml (version from WYGTV_VERSION_CODE or GITHUB_RUN_NUMBER) and the icon
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import { legacyCss } from './legacy-css.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const repo = path.join(root, '..');
const desktop = path.join(repo, 'WygDesktop', 'src');
const www = path.join(root, 'www');
const nm = (p) => path.join(root, 'node_modules', p);
const TARGET = 'chrome69';

fs.rmSync(www, { recursive: true, force: true });
fs.cpSync(path.join(desktop, 'renderer'), www, { recursive: true });
fs.mkdirSync(path.join(www, 'vendor'), { recursive: true });
fs.copyFileSync(nm('hls.js/dist/hls.min.js'), path.join(www, 'vendor', 'hls.min.js'));
fs.copyFileSync(nm('mpegts.js/dist/mpegts.js'), path.join(www, 'vendor', 'mpegts.js'));
fs.copyFileSync(nm('fflate/umd/index.js'), path.join(www, 'vendor', 'fflate.js'));
fs.copyFileSync(path.join(root, 'web', 'tizen-bridge.js'), path.join(www, 'js', 'tizen-bridge.js'));
fs.copyFileSync(path.join(root, 'web', 'tizen-avplay.js'), path.join(www, 'js', 'tizen-avplay.js'));
fs.copyFileSync(path.join(root, 'web', 'tizen.css'), path.join(www, 'tizen.css'));
fs.copyFileSync(path.join(repo, 'docs', 'img', 'icon-512.png'), path.join(www, 'icon.png'));

// ------------------------------------------------------------------ desktop main-process modules, run in the page
// Node built-ins they mention but never use on the TV (UDP discovery, gzip of Buffers).
const shims = {
  zlib: '{}', string_decoder: '{}', os: '{ networkInterfaces: () => ({}) }',
  dgram: "{ createSocket() { throw new Error('no UDP on Samsung TVs'); } }",
  './net': 'window.__wygNet',
};
let mods = "'use strict';\n/* Generated by scripts/build.mjs from WygDesktop/src/main. Do not edit. */\n(function () {\n  const defs = {}, cache = {};\n";
mods += '  const shims = {' + Object.entries(shims).map(([k, v]) => `${JSON.stringify(k)}: () => (${v})`).join(', ') + '};\n';
mods += '  function require(name) {\n    if (shims[name]) return shims[name]();\n    if (cache[name]) return cache[name].exports;\n    const module = cache[name] = { exports: {} };\n    defs[name](module, module.exports, require);\n    return module.exports;\n  }\n';
for (const m of ['m3u', 'xmltv', 'hdhr', 'tablo']) {
  const src = fs.readFileSync(path.join(desktop, 'main', m + '.js'), 'utf8');
  mods += `  defs['./${m}'] = function (module, exports, require) {\n${src}\n  };\n`;
}
mods += '  window.__wygRequire = require;\n})();\n';
fs.writeFileSync(path.join(www, 'js', 'desktop-modules.js'), mods);

const cssIn = fs.readFileSync(path.join(www, 'styles.css'), 'utf8');
const { css: cssLegacy, aspect } = legacyCss(cssIn);
fs.writeFileSync(path.join(www, 'styles.css'), cssLegacy);

const legacyJs = fs.readFileSync(path.join(root, 'web', 'tizen-legacy.js'), 'utf8')
  .replace('/*@ASPECT@*/[]', JSON.stringify(aspect));
if (legacyJs.includes('@ASPECT@')) throw new Error('web/tizen-legacy.js lost its @ASPECT@ marker');
fs.writeFileSync(path.join(www, 'js', 'tizen-legacy.js'), legacyJs);

// ------------------------------------------------------------------ index.html
let html = fs.readFileSync(path.join(www, 'index.html'), 'utf8');
html = html
  .replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="viewport" content="width=1920, user-scalable=no">')
  .replace('<title>WygDesktop</title>', '<title>WygTV</title>')
  .replace('<link rel="stylesheet" href="styles.css">', '<link rel="stylesheet" href="styles.css">\n  <link rel="stylesheet" href="tizen.css">\n  <script src="js/tizen-legacy.js"></script>')
  .replace('../../node_modules/hls.js/dist/hls.min.js', 'vendor/hls.min.js')
  .replace('../../node_modules/mpegts.js/dist/mpegts.js', 'vendor/mpegts.js')
  // Samsung's TV APIs (AVPlay, product info); $WEBAPIS is filled in by the TV.
  .replace('<script src="js/core.js"></script>',
    '<script src="$WEBAPIS/webapis/webapis.js"></script>\n  <script src="vendor/fflate.js"></script>\n  <script src="js/desktop-modules.js"></script>\n  <script src="js/tizen-avplay.js"></script>\n  <script src="js/tizen-bridge.js"></script>\n  <script src="js/core.js"></script>');
for (const need of ['vendor/fflate.js', 'vendor/hls.min.js', 'vendor/mpegts.js', 'js/tizen-avplay.js', 'js/tizen-bridge.js', 'js/tizen-legacy.js', 'tizen.css', 'name="viewport"', '$WEBAPIS']) {
  if (!html.includes(need)) throw new Error('index.html did not get ' + need);
}
fs.writeFileSync(path.join(www, 'index.html'), html);

// ------------------------------------------------------------------ lower JavaScript and CSS to Chrome 69
function walk(dir) { return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])); }
for (const f of walk(www)) {
  const ext = path.extname(f);
  if (ext !== '.js' && ext !== '.css') continue;
  const r = await esbuild.transform(fs.readFileSync(f, 'utf8'), { loader: ext.slice(1), target: TARGET, charset: 'utf8', legalComments: 'inline' });
  for (const w of r.warnings) console.warn(path.relative(www, f) + ': ' + w.text);
  fs.writeFileSync(f, r.code);
}

// ------------------------------------------------------------------ config.xml
// Tizen versions are x.y.z with z up to 65535, so the build number goes last (1.0.<build>), as on Android.
const build = process.env.WYGTV_VERSION_CODE || process.env.GITHUB_RUN_NUMBER || '0';
if (!/^\d{1,5}$/.test(build) || +build > 65535) throw new Error('build number must be 0–65535, got ' + build);
fs.writeFileSync(path.join(www, 'config.xml'), fs.readFileSync(path.join(root, 'config.xml'), 'utf8').replace('@VERSION@', '1.0.' + build));

console.log(`www/ is ready (WygTV 1.0.${build} for Samsung TVs; ${aspect.length} aspect-ratio rules)`);
