// Builds WygTV for Samsung Smart TVs (Tizen) from WygDesktop's screens: node scripts/build.mjs [version]
// - copies WygDesktop/src/renderer into build/app
// - bundles the desktop's m3u.js, xmltv.js, hdhr.js and tablo.js to run in the page (js/desktop-modules.js)
// - adds web/tizen-bridge.js (stands in for the desktop app's main process), hls.js, mpegts.js and fflate
// - lowers the JavaScript for 2020 and newer TVs (Tizen 5.5, Chromium 69) with esbuild
// - writes config.xml and zips it all into dist/WygTV.wgt (unsigned: sign it with your Samsung certificate)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import * as esbuild from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const desktop = path.join(root, '..', 'WygDesktop', 'src');
const app = path.join(root, 'build', 'app');
const dist = path.join(root, 'dist');
const nm = (p) => path.join(root, 'node_modules', p);
const version = process.argv[2] || process.env.WYG_VERSION || '1.0.0';
const TARGET = 'chrome69';

fs.rmSync(path.join(root, 'build'), { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
fs.cpSync(path.join(desktop, 'renderer'), app, { recursive: true });
fs.mkdirSync(path.join(app, 'vendor'), { recursive: true });
fs.copyFileSync(nm('hls.js/dist/hls.min.js'), path.join(app, 'vendor', 'hls.min.js'));
fs.copyFileSync(nm('mpegts.js/dist/mpegts.js'), path.join(app, 'vendor', 'mpegts.js'));
fs.copyFileSync(nm('fflate/umd/index.js'), path.join(app, 'vendor', 'fflate.js'));
fs.copyFileSync(path.join(root, 'web', 'tizen-bridge.js'), path.join(app, 'js', 'tizen-bridge.js'));
fs.copyFileSync(path.join(root, 'web', 'tizen.css'), path.join(app, 'tizen.css'));

// Node built-ins the reused modules mention but never use on a TV (UDP discovery, gzip of Buffers).
const shims = {
  zlib: '{}', string_decoder: '{}', os: '{ networkInterfaces: () => ({}) }', stream: '{}',
  dgram: "{ createSocket() { throw new Error('no UDP in a TV app'); } }",
  './net': 'window.__wygNet',
};
let out = "'use strict';\n/* Generated by WygTV-Tizen/scripts/build.mjs from WygDesktop/src/main. Do not edit. */\n(function () {\n  const defs = {}, cache = {};\n";
out += '  const shims = {' + Object.entries(shims).map(([k, v]) => `${JSON.stringify(k)}: () => (${v})`).join(', ') + '};\n';
out += '  function require(name) {\n    if (shims[name]) return shims[name]();\n    if (cache[name]) return cache[name].exports;\n    const module = cache[name] = { exports: {} };\n    defs[name](module, module.exports, require);\n    return module.exports;\n  }\n';
for (const m of ['m3u', 'xmltv', 'hdhr', 'tablo']) {
  const src = fs.readFileSync(path.join(desktop, 'main', m + '.js'), 'utf8');
  out += `  defs['./${m}'] = function (module, exports, require) {\n${src}\n  };\n`;
}
out += '  window.__wygRequire = require;\n})();\n';
fs.writeFileSync(path.join(app, 'js', 'desktop-modules.js'), out);

// Lower newer syntax (?. ?? ||= …) for older TVs. Each file stays a plain script.
for (const f of fs.readdirSync(path.join(app, 'js')).filter((f) => f.endsWith('.js'))) {
  const p = path.join(app, 'js', f);
  const r = await esbuild.transform(fs.readFileSync(p, 'utf8'), { loader: 'js', target: TARGET, charset: 'utf8', legalComments: 'none' });
  fs.writeFileSync(p, r.code);
}

let html = fs.readFileSync(path.join(app, 'index.html'), 'utf8');
html = html
  .replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="viewport" content="width=1920, user-scalable=no">')
  .replace('<title>WygDesktop</title>', '<title>WygTV</title>')
  .replace('../../node_modules/hls.js/dist/hls.min.js', 'vendor/hls.min.js')
  .replace('../../node_modules/mpegts.js/dist/mpegts.js', 'vendor/mpegts.js')
  .replace('<script src="js/core.js"></script>',
    '<script src="vendor/fflate.js"></script>\n  <script src="js/desktop-modules.js"></script>\n  <script src="js/tizen-bridge.js"></script>\n  <link rel="stylesheet" href="tizen.css">\n  <script src="js/core.js"></script>');
for (const need of ['vendor/hls.min.js', 'vendor/mpegts.js', 'js/tizen-bridge.js', 'vendor/fflate.js', 'name="viewport"']) {
  if (!html.includes(need)) throw new Error('index.html did not get ' + need);
}
fs.writeFileSync(path.join(app, 'index.html'), html);

// Tizen wants x.y.z with each part small: 1.0.<build> → 1.0.<build> while it fits, else 1.<build/1000>.<rest>.
const [a, b, c] = version.split('.').map((n) => parseInt(n, 10) || 0);
const tizenVersion = c > 65535 ? `${a}.${b + Math.floor(c / 1000)}.${c % 1000}` : `${a}.${b}.${c}`;
const config = fs.readFileSync(path.join(root, 'config.xml'), 'utf8').replace('@VERSION@', tizenVersion);
fs.writeFileSync(path.join(app, 'config.xml'), config);
fs.copyFileSync(path.join(desktop, 'renderer', 'assets', 'icon.png'), path.join(app, 'icon.png'));
fs.writeFileSync(path.join(dist, 'tizen-version.json'), JSON.stringify({ version: tizenVersion }) + '\n');

// A .wgt is a zip of the app folder, config.xml at its root.
const wgt = path.join(dist, 'WygTV.wgt');
fs.rmSync(wgt, { force: true });
execFileSync('zip', ['-q', '-r', '-X', wgt, '.'], { cwd: app });
console.log('dist/WygTV.wgt is ready (version ' + tizenVersion + ', unsigned)');
