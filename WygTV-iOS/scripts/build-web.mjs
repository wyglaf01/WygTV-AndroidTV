// Builds www/ (the app's pages) from WygDesktop's screens: node scripts/build-web.mjs
// - copies WygDesktop/src/renderer
// - adds hls.js, mpegts.js and Capacitor's core script (vendor/)
// - wraps the desktop's m3u.js, xmltv.js and hdhr.js so they run in the page (js/desktop-modules.js)
// - adds web/ios-bridge.js, which stands in for the desktop app's main process
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const desktop = path.join(root, '..', 'WygDesktop', 'src');
const www = path.join(root, 'www');
const nm = (p) => path.join(root, 'node_modules', p);

fs.rmSync(www, { recursive: true, force: true });
fs.cpSync(path.join(desktop, 'renderer'), www, { recursive: true });
fs.mkdirSync(path.join(www, 'vendor'), { recursive: true });
fs.copyFileSync(nm('hls.js/dist/hls.min.js'), path.join(www, 'vendor', 'hls.min.js'));
fs.copyFileSync(nm('mpegts.js/dist/mpegts.js'), path.join(www, 'vendor', 'mpegts.js'));
fs.copyFileSync(nm('@capacitor/core/dist/capacitor.js'), path.join(www, 'vendor', 'capacitor.js'));
fs.copyFileSync(path.join(root, 'web', 'ios-bridge.js'), path.join(www, 'js', 'ios-bridge.js'));

// Node built-ins the reused modules mention but never use on iOS (UDP discovery, gzip of Buffers).
const shims = {
  zlib: '{}', string_decoder: '{}', os: '{ networkInterfaces: () => ({}) }',
  dgram: "{ createSocket() { throw new Error('no UDP on iOS'); } }",
  './net': 'window.__wygNet',
};
let out = "'use strict';\n/* Generated by scripts/build-web.mjs from WygDesktop/src/main. Do not edit. */\n(function () {\n  const defs = {}, cache = {};\n";
out += '  const shims = {' + Object.entries(shims).map(([k, v]) => `${JSON.stringify(k)}: () => (${v})`).join(', ') + '};\n';
out += '  function require(name) {\n    if (shims[name]) return shims[name]();\n    if (cache[name]) return cache[name].exports;\n    const module = cache[name] = { exports: {} };\n    defs[name](module, module.exports, require);\n    return module.exports;\n  }\n';
for (const m of ['m3u', 'xmltv', 'hdhr']) {
  const src = fs.readFileSync(path.join(desktop, 'main', m + '.js'), 'utf8');
  out += `  defs['./${m}'] = function (module, exports, require) {\n${src}\n  };\n`;
}
out += '  window.__wygRequire = require;\n})();\n';
fs.writeFileSync(path.join(www, 'js', 'desktop-modules.js'), out);

let html = fs.readFileSync(path.join(www, 'index.html'), 'utf8');
html = html
  .replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1, user-scalable=no">')
  .replace("default-src 'self' file:", "default-src 'self' file: capacitor:")
  .replace('<title>WygDesktop</title>', '<title>WygTV-iOS</title>')
  .replace('../../node_modules/hls.js/dist/hls.min.js', 'vendor/hls.min.js')
  .replace('../../node_modules/mpegts.js/dist/mpegts.js', 'vendor/mpegts.js')
  .replace('<script src="js/core.js"></script>',
    '<script src="vendor/capacitor.js"></script>\n  <script src="js/desktop-modules.js"></script>\n  <script src="js/ios-bridge.js"></script>\n  <link rel="stylesheet" href="ios.css">\n  <script src="js/core.js"></script>');
for (const need of ['vendor/hls.min.js', 'vendor/mpegts.js', 'js/ios-bridge.js', 'name="viewport"']) {
  if (!html.includes(need)) throw new Error('index.html did not get ' + need);
}
fs.writeFileSync(path.join(www, 'index.html'), html);
fs.copyFileSync(path.join(root, 'web', 'ios.css'), path.join(www, 'ios.css'));
console.log('www/ is ready');
